import { expect, test } from '@playwright/test'

test('shortage, substitution, evidence and human approval', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('Backend connected')).toBeVisible()
  await page.getByRole('button', { name: /The fabric shortfall/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Analyze project' }).click()
  await expect(page.getByRole('heading', { name: 'Resolve constraints before approval' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review estimate' })).toBeDisabled()
  await expect(page.getByText('40.69 lm shortfall')).toBeVisible()
  await page.getByRole('tab', { name: 'Agent findings' }).click()
  await expect(page.getByRole('heading', { name: 'Inventory agent', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Inspect tool evidence' }).nth(1).click()
  await expect(page.locator('pre.evidence')).toContainText('68.69')
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'Use & re-analyze' }).click()
  await expect(page.getByRole('heading', { name: 'Estimate ready for human review' })).toBeVisible()
  await page.getByRole('tab', { name: 'Quotation', exact: true }).click()
  await expect(page.locator('.quote-totals .total')).toContainText('20,404.27')
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'Review estimate' }).click()
  await page.getByLabel('Reviewer name').fill('Interview reviewer')
  await page.getByLabel('I reviewed the sample measurements and survey assumptions.').check()
  await page.getByLabel('I reviewed the product, fabric and installation checklist.').check()
  await page.getByLabel('I reviewed the cost breakdown, deadline and exclusions.').check()
  await page.getByRole('button', { name: 'Approve demo estimate' }).click()
  await expect(page.getByText('Demo estimate approved by Interview reviewer. No operational actions executed.')).toBeVisible()
  await page.getByRole('button', { name: /Project reports/ }).click()
  await expect(page.getByRole('cell', { name: 'Demo approved', exact: true }).first()).toBeVisible()
  expect(errors).toEqual([])
})

test('urgent deadline and mobile layout', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: /The urgent fit-out/ }).click()
  await page.getByRole('button', { name: 'Analyze project' }).click()
  await expect(page.getByRole('heading', { name: 'Resolve constraints before approval' })).toBeVisible()
  await page.getByRole('tab', { name: 'Production & quality' }).click()
  await expect(page.getByText('Deadline at risk', { exact: true })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
})

